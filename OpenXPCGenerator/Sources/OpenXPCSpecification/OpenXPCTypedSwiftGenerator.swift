import Foundation

internal enum OpenXPCTypedSwiftGenerator {
	static func render(_ schema: OpenXPCDataSchema, operations allowed: [String],
		additionalTypes: [String] = []) -> String {
		let selected = schema.operations.filter { allowed.contains($0.name) }
		let lookup = Dictionary(uniqueKeysWithValues: schema.types.map { ($0.name, $0) })
		var required: Set<String> = []
		func include(_ name: String) {
			guard
				required.insert(name).inserted,
				let definition = lookup[name]
			else { return }
			for field in definition.fields where lookup[field.type] != nil { include(field.type) }
		}
		for operation in selected {
			include(operation.request)
			include(operation.response)
		}
		for name in additionalTypes { include(name) }
		let definitions = schema.types.filter { required.contains($0.name) }
		var result = """
			import Foundation

			// Generated by OpenXPCGenerator. Do not edit.
			public enum OpenXPCGeneratedDataError: Error {
				case invalidField(String)
			}

			private struct _OpenXPCAnyCodingKey: CodingKey {
				let stringValue: String
				var intValue: Int? { nil }
				init?(stringValue: String) { self.stringValue = stringValue }
				init?(intValue: Int) { return nil }
			}
			"""
		for definition in definitions {
			result += "\n\n" + render(definition)
		}
		return result + "\n"
	}

	private static func render(_ definition: OpenXPCDataSchema.Definition) -> String {
		var lines = ["public struct \(definition.name): Codable, Equatable, Sendable {"]
		for field in definition.fields {
			lines.append("\tpublic let \(field.name): \(swiftType(field))")
		}
		let parameters = definition.fields.map { "\($0.name): \(swiftType($0))" }.joined(
			separator: ", ")
		lines.append("\tpublic init(\(parameters)) throws {")
		for field in definition.fields {
			let body = checks(field, in: definition.name)
			if field.optional, !body.isEmpty {
				lines.append("\t\tif let \(field.name) {")
				lines.append(contentsOf: body.map { "\t" + $0 })
				lines.append("\t\t}")
			} else {
				lines.append(contentsOf: body)
			}
			lines.append("\t\tself.\(field.name) = \(field.name)")
		}
		lines.append("\t}")
		if !definition.fields.isEmpty {
			lines.append("\tprivate enum CodingKeys: String, CodingKey {")
			for field in definition.fields { lines.append("\t\tcase \(field.name)") }
			lines.append("\t}")
		}
		lines.append("\tpublic init(from decoder: Decoder) throws {")
		lines.append("\t\tlet unknown = try decoder.container(keyedBy: _OpenXPCAnyCodingKey.self)")
		let known = definition.fields.map { String(reflecting: $0.name) }.joined(separator: ", ")
		lines.append("\t\tlet permitted: Set<String> = [\(known)]")
		lines.append(
			"\t\tguard Set(unknown.allKeys.map(\\.stringValue)).isSubset(of: permitted) else {")
		lines.append(
			"\t\t\tthrow DecodingError.dataCorrupted(.init(codingPath: decoder.codingPath, debugDescription: \"unknown field\"))"
		)
		lines.append("\t\t}")
		if !definition.fields.isEmpty {
			lines.append("\t\tlet container = try decoder.container(keyedBy: CodingKeys.self)")
			for field in definition.fields {
				let decodedType = swiftType(field, optional: false)
				let method = field.optional ? "decodeIfPresent" : "decode"
				lines.append(
					"\t\tlet \(field.name) = try container.\(method)(\(decodedType).self, forKey: .\(field.name))"
				)
			}
		}
		let arguments = definition.fields.map { "\($0.name): \($0.name)" }.joined(separator: ", ")
		lines.append("\t\ttry self.init(\(arguments))")
		lines.append("\t}")
		lines.append("}")
		return lines.joined(separator: "\n")
	}

	private static func swiftType(_ field: OpenXPCDataSchema.Field, optional: Bool? = nil) -> String {
		let base: String
		switch field.type {
		case "string": base = "String"
		case "int": base = "Int"
		case "bool": base = "Bool"
		case "double": base = "Double"
		case "data": base = "Data"
		case "uuid": base = "UUID"
		default: base = field.type
		}
		let value = field.array ? "[\(base)]" : base
		return (optional ?? field.optional) ? value + "?" : value
	}

	private static func checks(_ field: OpenXPCDataSchema.Field, in owner: String) -> [String] {
		let error =
			"throw OpenXPCGeneratedDataError.invalidField(\(String(reflecting: owner + "." + field.name)))"
		var result: [String] = []
		if let maximum = field.maxItems {
			result.append("\t\tguard \(field.name).count <= \(maximum) else { \(error) }")
		}
		let size: String?
		if field.maxLength != nil {
			size = ".utf8.count"
		} else if field.maxBytes != nil {
			size = ".count"
		} else {
			size = nil
		}
		if let size, let maximum = field.maxLength ?? field.maxBytes {
			if field.array {
				result.append(
					"\t\tguard \(field.name).allSatisfy({ $0\(size) <= \(maximum) }) else { \(error) }")
			} else {
				result.append("\t\tguard \(field.name)\(size) <= \(maximum) else { \(error) }")
			}
		}
		return result
	}
}
